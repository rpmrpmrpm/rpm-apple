/// The glyphs of the library and home features: the descriptions' language, the playing
/// history, Quick selection. Font Awesome's, as every other ``Glyph``.
extension Glyph {
    /// A globe, for the language of the artist and album descriptions.
    static let globe = "\u{f0ac}"

    /// A clock turning back, for the songs played lately.
    static let history = "\u{f1da}"

    /// A bolt, for Quick selection.
    static let quick = "\u{f0e7}"
}
