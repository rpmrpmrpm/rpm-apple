import Foundation

/// One licence. `file` is the name of a file in this module's `Licenses` resource folder. It is nil when
/// the licence is a published set of terms that only its publisher may host. In that case the screen can
/// offer a link only.
///
/// `isNotices` marks an aggregate notices document, not a single licence. It holds hundreds of kilobytes
/// of text that the parts of a native library require to be distributed with it. It ships under `file`.
/// The screen sends the reader to `url` instead of showing it, because the text is too long for one block.
public struct CreditLicense: Sendable, Equatable {
    public let name: String
    public let file: String?
    public let url: String?
    public let isNotices: Bool

    public init(name: String, file: String?, url: String?, isNotices: Bool = false) {
        self.name = name
        self.file = file
        self.url = url
        self.isNotices = isNotices
    }
}

/// One thing that rpm ships or uses.
///
/// `use` is a key in the string table. It says what rpm uses this for. `source` is set only where a licence
/// requires an offer of the source, so it is not simply the project link. `termsUrl` is the address of the
/// terms, for an entry whose licence has no address of its own.
public struct CreditEntry: Sendable, Equatable, Identifiable {
    public let name: String
    public let version: String?
    public let detail: String?
    public let copyright: String?
    public let url: String?
    public let source: String?
    public let use: String?
    public let termsUrl: String?
    public let licenses: [String]

    public var id: String { name + (detail ?? "") }

    public init(name: String, version: String?, detail: String?, copyright: String?,
                url: String?, source: String?, use: String?, termsUrl: String?,
                licenses: [String]) {
        self.name = name
        self.version = version
        self.detail = detail
        self.copyright = copyright
        self.url = url
        self.source = source
        self.use = use
        self.termsUrl = termsUrl
        self.licenses = licenses
    }
}

/// `note` is one sentence about the whole section. It is used where the entries need a statement that none
/// of them could carry alone.
public struct CreditSection: Sendable, Equatable, Identifiable {
    public let title: String
    public let note: String?
    public let entries: [CreditEntry]

    public var id: String { title }

    public init(title: String, note: String?, entries: [CreditEntry]) {
        self.title = title
        self.note = note
        self.entries = entries
    }
}

/// The acknowledgements: what the phone ships that other people made, and what it uses.
///
/// **The list is shorter than the desktop's, and this is correct.** This head is written in Swift on Apple's
/// own frameworks, and it carries no third-party code. So the list names the three typefaces it draws with
/// and the two services it calls. Naming ffmpeg or an ONNX model here, which the desktop uses, would state
/// something that is not on this device.
///
/// The list itself is in `CreditsData.swift`, generated by `scripts/gen_credits.py` from
/// `scripts/credits.json`. This file holds what the generated table cannot: the licence texts, which are
/// files and not strings, and the rule for reading them.
public enum Credits {
    /// Licence texts that have already been read, by file name.
    ///
    /// This is kept on the main actor, not behind a lock. Every reader is a SwiftUI view. The files are a few
    /// kilobytes each, read from the app bundle. An actor here would make the cache asynchronous to read,
    /// which would be slower than the file read it saves.
    @MainActor private static var read: [String: String] = [:]

    /// The bundle that holds the licence texts.
    ///
    /// This is named here for the same reason as `Loc.table`. `Bundle.module` is generated for each module.
    /// Inside a test it points at the test bundle, which has no licences, so every lookup returns nil. This
    /// property points at the bundle that has the folder.
    static var bundle: Bundle { .module }

    /// The text of a licence, with the holder's own copyright line filled in.
    ///
    /// The texts are the licences as published. Permissive licences carry a placeholder line instead of a
    /// name, such as MIT's `Copyright (c) <year> <copyright holders>`. The placeholder has to be filled in,
    /// because a licence that names nobody grants nothing.
    ///
    /// The substitution is narrow. It changes only a line whose copyright is in angle brackets, which is how
    /// the placeholder is written. The Open Font License has no such line. An Apache appendix shows how to
    /// apply the licence to your own work, and its example uses square brackets, which are not a
    /// placeholder. Neither text is changed.
    ///
    /// An entry with no copyright of its own has the placeholder line removed rather than left in place. A
    /// line of angle brackets on screen looks like an error in the app.
    @MainActor
    public static func text(of licence: CreditLicense, copyright: String?) -> String {
        guard let file = licence.file else { return "" }

        let whole: String
        if let already = read[file] {
            whole = already
        } else {
            guard let url = Credits.url(of: file),
                  let loaded = try? String(contentsOf: url, encoding: .utf8)
            else { return licence.url ?? "" }

            read[file] = loaded
            whole = loaded
        }

        return fill(whole, with: copyright)
    }

    /// The bundle location of one licence's text, or nil if it was not shipped.
    ///
    /// The `Licenses` subfolder is tried first, then the bundle root. The layout inside the built bundle is
    /// decided by the package manager, so this code does not depend on it.
    static func url(of file: String) -> URL? {
        let name = (file as NSString).deletingPathExtension
        return bundle.url(forResource: name, withExtension: "txt", subdirectory: "Licenses")
            ?? bundle.url(forResource: name, withExtension: "txt")
    }

    /// Puts `copyright` in place of the placeholder line. If there is no copyright, the gap is closed instead.
    ///
    /// This works line by line and not with a regular expression. The test is whether a line starts with
    /// `Copyright (c) <`. A multiline regex over 35,000 characters of the GPL would give the same answer more
    /// slowly and be harder to read.
    static func fill(_ text: String, with copyright: String?) -> String {
        var lines = text.components(separatedBy: "\n")

        guard let at = lines.firstIndex(where: { $0.hasPrefix("Copyright (c) <") }) else {
            return text
        }

        if let copyright, !copyright.isEmpty {
            lines[at] = copyright
        } else {
            // Remove the line and the blank line under it. Otherwise the licence opens with two empty
            // lines where a name would be.
            let through = at + 1 < lines.count && lines[at + 1].isEmpty ? at + 1 : at
            lines.removeSubrange(at...through)
        }

        return lines.joined(separator: "\n")
    }
}
